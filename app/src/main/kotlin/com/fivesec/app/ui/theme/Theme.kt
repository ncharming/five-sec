/** 浮层圆角统一 24dp：M3 弹窗/菜单读取 shapes.extraLarge；比卡片（22dp）略大，强化浮层语义。 */
private val FiveSecShapes = Shapes(extraLarge = RoundedCornerShape(24.dp))

@Composable
fun FiveSecTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColors else LightColors
    MaterialTheme(colorScheme = colorScheme, typography = Typography, shapes = FiveSecShapes, content = content)
}
